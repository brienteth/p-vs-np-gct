"""Test whether a 3D subspace of rows of P(a,b) can factor as W(b) A2(a)."""
import sys
sys.path.insert(0, '/Users/bl10buer/Desktop/matemk/p-vs-np-gct')
import numpy as np
from poly_exact import permanent_poly
from perm4_middle_factorization_probe import extract_middle_4x4
from apolar_higher_betti_probe import rank_matrix_mod
from perm4_abp_frontier import MOD

# Extract P(a,b)
perm_poly = permanent_poly(4)
p_mat = extract_middle_4x4(perm_poly)

# For any row combination gamma in C^4:
# R(gamma)(a, b) = sum_{j0=0}^3 gamma_{j0} P[j0, :](a,b)
# This is a 1x4 vector of bilinear forms in a and b.
# We want to know if for a 3-dimensional subspace of gamma (gamma in u^perp),
# all R(gamma)(a,b) factor through a COMMON 5x4 linear matrix A2(a):
# R(gamma)(a,b) = w_gamma(b)^T A2(a).

# Let us analyze what R(gamma)(a,b) = w(b)^T A2(a) means:
# For each j3 in {0..3}:
# R(gamma)_{j3}(a,b) = sum_{k=1}^5 w_k(b) A_{2, k, j3}(a).
# This means for a fixed gamma, the bilinear form in (a,b) has b-rank at most 5.
# But more strongly: for ALL gamma in u^perp (a 3D space of gamma):
# The rows of P(a,b) restricted to u^perp have their a-dependence generated by
# the entries of A2(a), which has size 5x4.
# A2(a) has 5*4 = 20 entries, each linear in a0..a3.
# But notice: the space of bilinear forms in R(gamma) as gamma varies in u^perp:
# u^perp has dimension 3.
# For 3 independent rows, say rows 0, 1, 2 of P(a,b):
# Let us check the rank of the partial derivatives with respect to b!
print("Analyzing rank of b-derivatives for rows of P(a,b)...")

# Represent each entry P[j0, j3] as a 4x4 matrix C_{j0, j3}[c1, c2] = coeff of a_c1 b_c2.
# So P[j0, j3](a,b) = a^T C_{j0, j3} b.
# If R(gamma)_{j3} = sum_k w_k(b) A_{2, k, j3}(a), then
# sum_{j0} gamma_{j0} C_{j0, j3} = sum_k (A_{2, k, j3}) (w_{\gamma, k})^T.
# Let us check the linear span of matrices C_{j0, j3} for j0 in u^perp!

C = np.zeros((4, 4, 4, 4), dtype=np.int64) # j0, j3, c1, c2
for j0 in range(4):
    for j3 in range(4):
        for mon, coeff in p_mat[j0][j3].items():
            c1 = [k for k in range(4) if mon[k] == 1][0]
            c2 = [k for k in range(4) if mon[4+k] == 1][0]
            C[j0, j3, c1, c2] = coeff

# For each j0, the 4 matrices C[j0, 0], C[j0, 1], C[j0, 2], C[j0, 3]:
for j0 in range(4):
    # Flatten each C[j0, j3] to 16
    m_j0 = C[j0].reshape(4, 16)
    print(f"Row j0={j0}: rank of 4x16 matrix = {rank_matrix_mod(m_j0, MOD)}")

# For 3 rows together (e.g. j0 in {0, 1, 2}), size is 12 x 16:
m_012 = C[0:3].reshape(12, 16)
print(f"Rows 0, 1, 2: rank of 12x16 matrix = {rank_matrix_mod(m_012, MOD)}")

# All 4 rows: 16 x 16:
m_all = C.reshape(16, 16)
print(f"All 4 rows: rank of 16x16 matrix = {rank_matrix_mod(m_all, MOD)}")
